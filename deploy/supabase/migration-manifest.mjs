import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const directory = new URL("../../migrations/", import.meta.url);
const migrations = readdirSync(directory).filter(name => /^\d+_.+\.sql$/.test(name)).sort().map(name => ({
  version: Number(name.split("_")[0]),
  checksum: createHash("sha384").update(readFileSync(new URL(name, directory))).digest("hex"),
}));
assert.ok(migrations.length > 0);
assert.equal(new Set(migrations.map(m => m.version)).size, migrations.length);
const sql = `-- Generated by node deploy/supabase/migration-manifest.mjs; do not edit.\nWITH expected(version, checksum) AS (VALUES\n${migrations.map(m => `  (${m.version}::bigint, decode('${m.checksum}', 'hex'))`).join(",\n")}\n), differences AS (\n  (SELECT version, checksum FROM expected EXCEPT SELECT version, checksum FROM _sqlx_migrations WHERE success)\n  UNION ALL\n  (SELECT version, checksum FROM _sqlx_migrations EXCEPT SELECT version, checksum FROM expected)\n)\nSELECT NOT EXISTS (SELECT 1 FROM differences) AND NOT EXISTS (SELECT 1 FROM _sqlx_migrations WHERE NOT success) AS migrations_match \\gset\n\\if :migrations_match\n\\else\n  \\echo 'Database migration versions/checksums do not match this release.'\n  DO $$ BEGIN RAISE EXCEPTION 'Migration verification failed'; END $$;\n\\endif\n`;
const output = new URL("expected-migrations.sql", import.meta.url);
if (process.argv.includes("--check")) {
  assert.equal(readFileSync(output, "utf8"), sql, "Run node deploy/supabase/migration-manifest.mjs after adding a migration");
} else writeFileSync(output, sql);
console.log(`${migrations.length} migration checksums verified: ${fileURLToPath(output)}`);
